const BADGE_TONES = {
  gray: 'bg-slate-100 text-slate-700 ring-slate-200',
  blue: 'bg-brand-50 text-brand-700 ring-brand-100',
  green: 'bg-emerald-50 text-emerald-700 ring-emerald-200',
  amber: 'bg-amber-50 text-amber-800 ring-amber-200',
  red: 'bg-red-50 text-red-700 ring-red-200',
} as const;
export type Tone = keyof typeof BADGE_TONES;

export function Badge({ tone = 'gray', children }: { tone?: Tone; children: ReactNode }) {
  return (
    <span className={clsx('inline-flex items-center rounded-full px-2 py-0.5 text-xs font-medium ring-1 ring-inset', BADGE_TONES[tone])}>
      {children}
    </span>
  );
}

export function StatusBadge({ status }: { status: string }) {
  const tone: Tone =
    ({
      COMPLETED: 'green',
      PROCESSED: 'green',
      VALID: 'green',
      RUNNING: 'blue',
      PROCESSING: 'blue',
      QUEUED: 'gray',
      UPLOADED: 'gray',
      PAUSED: 'amber',
      DUPLICATE: 'amber',
      FAILED: 'red',
      INVALID: 'red',
      CANCELLED: 'gray',
      APPROVED: 'green',
      QUALIFIED: 'green',
      VERIFIED: 'green',
      NEEDS_REVIEW: 'amber',
      UNVERIFIED: 'amber',
      REJECTED: 'red',
      NOT_QUALIFIED: 'red',
      PENDING: 'gray',
      DATA_UNAVAILABLE: 'gray',
      UNKNOWN: 'gray',
    } as Record<string, Tone>)[status] ?? 'gray';
  return <Badge tone={tone}>{(status.charAt(0) + status.slice(1).toLowerCase()).replace(/_/g, ' ')}</Badge>;
}

